[CmdletBinding()]
param(
  [string]$Dsh = 'dsh',
  [string]$Profile = 'cortex-bge',
  [string]$Package = 'dsh-cortex-memory',
  [string]$DataRoot = (Join-Path $HOME '.dsh\cortex-bge'),
  [string]$BaseUrl = 'http://127.0.0.1:11434/v1',
  [string]$Model = 'bge-m3',
  [int]$Dim = 1024
)

$ErrorActionPreference = 'Stop'
$dshCommand = Get-Command $Dsh -ErrorAction SilentlyContinue
if (-not $dshCommand) { throw "dsh command not found: $Dsh. Pass -Dsh with the path to dsh.cmd." }
$dshPath = $dshCommand.Source
$profilePath = Join-Path (Join-Path $HOME '.dsh\profiles') $Profile
if (Test-Path $profilePath) { throw "profile already exists: $profilePath. Choose another -Profile or remove it first." }

if ($Package -match '\.tgz$') {
  $Package = (Resolve-Path $Package).Path
}

& $dshPath --profile $Profile --from-default-profile web --dump-config | Out-Null
& $dshPath plugin --profile $Profile add $Package
if ($LASTEXITCODE -ne 0) { throw "plugin install failed with exit code $LASTEXITCODE" }

New-Item -ItemType Directory -Force -Path $DataRoot | Out-Null
$modelConfig = [ordered]@{
  embedding = [ordered]@{
    mode = 'local'
    baseUrl = $BaseUrl
    model = $Model
    dim = $Dim
    apiKey = ''
  }
  rerank = [ordered]@{
    enabled = $false
    baseUrl = ''
    model = ''
    apiKey = ''
  }
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText(
  (Join-Path $DataRoot 'model-config.json'),
  (($modelConfig | ConvertTo-Json -Depth 5) + "`n"),
  $utf8
)

$patchFile = Join-Path $profilePath 'cordis.patch.yml'
$patch = @"
# bge profile generated by examples/setup-cortex-bge.ps1
- id: cortex
  name: dsh-cortex
  config:
    dataRoot: '$($DataRoot.Replace('\','/'))'
    dbFile: '$((Join-Path $DataRoot 'cortex.sqlite').Replace('\','/'))'
    features:
      vector: true
"@
[System.IO.File]::WriteAllText($patchFile, $patch + "`n", $utf8)

Write-Host "profile: $profilePath"
Write-Host "dataRoot: $DataRoot"
Write-Host "Next: & '$dshPath' --profile $Profile --port 0 --no-open"
Write-Host "Start the local embedding service first: $BaseUrl"
